// Compile native Swift code for the demo app with the official Swift Android SDK.
val buildSwift by tasks.registering(Exec::class) {
    group = "build"
    description = "Build native Swift sources for Android"
    workingDir(rootProject.projectDir)
    commandLine("bash", "build-swift.sh")
}

// Stage swift-java Java sources into the build dir, excluding files that use
// `jdk.jfr` (unavailable on Android). Android-compatible replacements for the
// excluded annotations live in the app's own java source dir.
val stageSwiftJavaSources by tasks.registering(Sync::class) {
    group = "build"
    description = "Stage SwiftKitCore + jextract-generated Java sources for Android"
    dependsOn(buildSwift)
    into(layout.buildDirectory.dir("swift-java-staged"))
    from(rootProject.file(".build/checkouts/swift-java/SwiftKitCore/src/main/java")) {
        into("swiftkit-core")
        exclude("org/swift/swiftkit/core/annotations/Unsigned.java")
        exclude("org/swift/swiftkit/core/annotations/ThreadSafe.java")
    }
    from(rootProject.file(".build/plugins/outputs/demo/CatalogBridge/destination/JExtractSwiftPlugin/src/generated/java")) {
        into("jextract")
        exclude("jextract-generated-sources.txt")
    }
}

tasks.named("preBuild") {
    dependsOn(buildSwift)
    dependsOn(stageSwiftJavaSources)
}

